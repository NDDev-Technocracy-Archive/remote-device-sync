#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn physical_shortcuts_keep_sides_and_extended_navigation() {
        assert!(modifier(42));
        assert!(modifier(58));
        assert!(!modifier(30));
        assert_eq!((key(30), key(46), key(47)), (Some(0), Some(8), Some(9)));
        assert_eq!(
            (key(125), key(126), key(29), key(97)),
            (Some(55), Some(54), Some(59), Some(62))
        );
        assert_eq!(
            (key(105), key(106), key(103), key(108)),
            (Some(123), Some(124), Some(126), Some(125))
        );
        assert_eq!(
            (key(28), key(96), key(14), key(111)),
            (Some(36), Some(76), Some(51), Some(117))
        );
        for invalid in [0, 255, 65535, u32::MAX] {
            assert_eq!(key(invalid), None);
        }
    }
}
